def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", type=Path, metavar="HEADER",
        help="compare an existing header with the generated reference",
    )
    args = parser.parse_args()
    try:
        expected = render()
    except (OSError, subprocess.CalledProcessError) as error:
        print(f"Galatea reference ERROR: {error}", file=sys.stderr)
        return 1
    if args.check is None:
        print(expected, end="")
        return 0
    try:
        actual = args.check.read_text(encoding="utf-8")
    except OSError as error:
        print(f"Galatea reference ERROR: {error}", file=sys.stderr)
        return 1
    if actual != expected:
        print(f"Galatea reference MISMATCH: {args.check}", file=sys.stderr)
        return 1
    print("Galatea reference PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
