def lowpass(state: float, x: float, tau: int) -> float:
    """Original Galatea first-order integrator."""
    if tau < 1:
        raise ValueError(f"tau must be >= 1: {tau!r}")
    return state + (x - state) / tau


def hysteresis(prev_on: bool, x: float, band: float, center: float = 0.5) -> bool:
    """Original Galatea inclusive thresholds, retaining state inside the band."""
    if x >= center + band / 2.0:
        return True
    if x <= center - band / 2.0:
        return False
    return prev_on


def saturate(x: float, lo: float, hi: float) -> tuple[float, bool]:
    """Original Galatea bounded publication."""
    if x < lo:
        return lo, True
    if x > hi:
        return hi, True
    return x, False


@dataclass(frozen=True, slots=True)
class ValenceUpdate:
    """Original Galatea separates internal smoothing from publication."""

    raw: float
    smoothed: float
    published: float
    saturation_hit: bool


def valence_step(
    prev_smoothed: float, error_now: float, error_prev: float, tau_int: int,
) -> ValenceUpdate:
    """Original Galatea negative error delta, integration, then publication."""
    raw = -(error_now - error_prev)
    smoothed = lowpass(prev_smoothed, raw, tau_int)
    published, hit = saturate(smoothed, -1.0, 1.0)
    return ValenceUpdate(raw=raw, smoothed=smoothed, published=published, saturation_hit=hit)


def c_float(value: float) -> str:
    text = format(value, ".12f").rstrip("0").rstrip(".")
    if "." not in text:
        text += ".0"
    return text + "f"


def c_bool(value: bool) -> str:
    return "true" if value else "false"


