"""Check first-party C formatting and the whitespace hygiene of tracked text.

clang-format, pinned to the version that produced the current layout, runs in
--dry-run mode over every first-party C file and header. A whitespace check
covers every other tracked text file as well.

Not restored from the legacy tree: the kernel checkpatch gate. A strict run
over the current sources reports 951 findings in 127 files, dominated by
block-comment and SPDX comment conventions that differ from the reviewed
clang-format layout. Enabling it is a style-convention decision.

Pinned bytes are exempt from the whitespace check: patches/*.patch (SHA-256
pinned; some context lines are a single space), the upstream TweetNaCl
sources and the captured evidence logs. The formatter skips the upstream
TweetNaCl sources and the generated factory artifacts.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

CLANG_FORMAT_VERSION = "23.1.5"
THIRD_PARTY_C = (
    "framework/services/package/crypto/tweetnacl.c",
    "framework/services/package/crypto/tweetnacl.h",
)
# Factory artifacts are generated by the packer and pinned by SHA-256 in the
# firmware build; they keep the generator's layout.
GENERATED_C = ("factory/forge/artifacts/",)
WHITESPACE_EXEMPT = ("patches/", "docs/evidence/")
TEXT_SUFFIXES = {
    ".c",
    ".h",
    ".inc",
    ".py",
    ".md",
    ".json",
    ".yml",
    ".yaml",
    ".txt",
    ".conf",
    ".overlay",
    ".dts",
    ".dtsi",
    ".cmake",
    ".sh",
    ".toml",
    ".lock",
    ".rst",
    ".sum",
}
DEVIATION = re.compile(r"^(.+?):\d+:\d+: error:", re.MULTILINE)


def tracked(root):
    out = subprocess.check_output(["git", "-C", str(root), "ls-files", "-z"])
    return [name for name in out.decode().split("\0") if name]


def whitespace_errors(root, names):
    """Trailing whitespace, space-before-tab, CR, BOM and missing final newline."""
    errors = []
    for name in names:
        if name.startswith(WHITESPACE_EXEMPT) or name in THIRD_PARTY_C:
            continue
        if Path(name).suffix not in TEXT_SUFFIXES:
            continue
        data = (root / name).read_bytes()
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            errors.append(f"{name}: not UTF-8")
            continue
        if data.startswith(b"\xef\xbb\xbf"):
            errors.append(f"{name}: UTF-8 byte order mark")
        if "\r" in text:
            errors.append(f"{name}: carriage return")
        if text and not text.endswith("\n"):
            errors.append(f"{name}: no newline at end of file")
        for number, line in enumerate(text.split("\n"), 1):
            indent = line[: len(line) - len(line.lstrip(" \t"))]
            if line != line.rstrip(" \t"):
                errors.append(f"{name}:{number}: trailing whitespace")
            if " \t" in indent:
                errors.append(f"{name}:{number}: space before tab in indentation")
    return errors


def clang_format_errors(root, names, binary):
    """First-party sources whose formatting differs from the pinned clang-format."""
    try:
        version = subprocess.run([binary, "--version"], capture_output=True, text=True)
    except FileNotFoundError as exc:
        raise ValueError(
            f"clang-format {CLANG_FORMAT_VERSION} not found at {binary!r}; "
            "activate .venv or pass --clang-format"
        ) from exc
    if version.returncode != 0 or f"version {CLANG_FORMAT_VERSION}" not in (
        version.stdout
    ):
        raise ValueError(
            f"clang-format {CLANG_FORMAT_VERSION} is required, got: "
            f"{(version.stdout or version.stderr).strip()}"
        )
    if not names:
        return []
    result = subprocess.run(
        [binary, "--dry-run", "--Werror", *names],
        cwd=root,
        capture_output=True,
        text=True,
    )
    return sorted(set(DEVIATION.findall(result.stderr)))


def check(root, clang_format):
    """Return (errors, number of first-party C sources checked)."""
    names = tracked(root)
    errors = whitespace_errors(root, names)
    sources = [
        name
        for name in names
        if name.endswith((".c", ".h"))
        and name not in THIRD_PARTY_C
        and not name.startswith(GENERATED_C)
    ]
    errors += [
        f"{name}: formatting differs from clang-format {CLANG_FORMAT_VERSION}"
        for name in clang_format_errors(root, sources, clang_format)
    ]
    return errors, len(sources)


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parents[1]
    )
    parser.add_argument(
        "--clang-format",
        default="clang-format",
        help=f"clang-format {CLANG_FORMAT_VERSION} executable",
    )
    args = parser.parse_args()
    try:
        errors, count = check(args.root, args.clang_format)
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1
    for error in errors:
        print(f"FAIL: {error}", file=sys.stderr)
    if errors:
        return 1
    print(
        f"PASS: {count} first-party C sources match clang-format "
        f"{CLANG_FORMAT_VERSION}; whitespace hygiene of tracked text files clean"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
