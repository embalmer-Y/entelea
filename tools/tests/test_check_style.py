"""Check the first-party style and whitespace gate and its exact exemptions."""

import importlib.util
import stat
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "tools" / (name + ".py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


STYLE = load("check_style")


class StyleTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.binary = self.root / "clang-format"
        self.fake(self.fake_version(STYLE.CLANG_FORMAT_VERSION))

    def fake_version(self, version):
        return (
            f"#!{sys.executable}\n"
            "import sys\n"
            "if '--version' in sys.argv:\n"
            f"    print('clang-format version {version}')\n"
            "    sys.exit(0)\n"
            "bad = [p for p in sys.argv if p.endswith(('.c', '.h')) "
            "and 'UNFORMATTED' in open(p).read()]\n"
            "for p in bad:\n"
            "    print(f'{p}:1:1: error: code should be clang-formatted', "
            "file=sys.stderr)\n"
            "sys.exit(1 if bad else 0)\n"
        )

    def fake(self, text):
        self.binary.write_text(text)
        self.binary.chmod(self.binary.stat().st_mode | stat.S_IXUSR)

    def add(self, path, text):
        file = self.root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_bytes(text.encode())
        self.git("add", path)

    def git(self, *args):
        import subprocess

        subprocess.run(["git", "-C", str(self.root), *args], check=True)

    def setUp_repo(self):
        self.git("init", "-q")
        self.add("framework/a.c", "int a(void)\n{\n\treturn 0;\n}\n")

    def errors(self):
        return STYLE.check(self.root, str(self.binary))[0]

    def test_clean_tree_passes(self):
        self.setUp_repo()
        self.assertEqual(self.errors(), [])

    def test_trailing_whitespace_and_space_before_tab(self):
        self.setUp_repo()
        self.add("platform/b.c", "int b(void) \n{\n \treturn 1;\n}\n")
        self.assertEqual(
            self.errors(),
            [
                "platform/b.c:1: trailing whitespace",
                "platform/b.c:3: space before tab in indentation",
            ],
        )

    def test_missing_final_newline_carriage_return_and_bom(self):
        self.setUp_repo()
        self.add("docs/x.md", "text")
        self.add("docs/y.md", "line\r\nnext\n")
        self.add("docs/z.md", "\ufeffbom\n")
        self.assertEqual(
            self.errors(),
            [
                "docs/x.md: no newline at end of file",
                "docs/y.md: carriage return",
                "docs/z.md: UTF-8 byte order mark",
            ],
        )

    def test_pinned_bytes_are_exempt(self):
        self.setUp_repo()
        # Patches are pinned by SHA-256 and some context lines are one space.
        self.add("patches/x.patch", " context line\n+next \n")
        self.add("docs/evidence/run.txt", "captured output \n")
        self.add(
            "framework/services/package/crypto/tweetnacl.c",
            "int unformatted(void) { return 0; } /* UNFORMATTED */ \n",
        )
        self.assertEqual(self.errors(), [])

    def test_generated_factory_artifact_keeps_the_packer_layout(self):
        # factory_pkg.h is generated by tsap_pack.py and SHA-256 pinned by the
        # firmware build, so the formatter must never report or touch it.
        self.setUp_repo()
        self.add(
            "factory/forge/artifacts/run001/factory_pkg.h",
            "/* UNFORMATTED */\nint x(void) { return 0; }\n",
        )
        self.assertEqual(self.errors(), [])

    def test_binary_and_unknown_suffixes_are_not_scanned_for_whitespace(self):
        self.setUp_repo()
        self.add("docs/evidence/board.log", "captured output \n")
        self.add("artifacts/app.wasm", "binary \n")
        self.assertEqual(self.errors(), [])

    def test_formatting_deviation_is_reported(self):
        self.setUp_repo()
        self.add("platform/c.c", "/* UNFORMATTED */\nint c(void) { return 0; }\n")
        self.assertEqual(
            self.errors(),
            [
                "platform/c.c: formatting differs from clang-format "
                f"{STYLE.CLANG_FORMAT_VERSION}"
            ],
        )

    def test_other_clang_format_version_is_refused(self):
        self.setUp_repo()
        self.fake(self.fake_version("20.1.8"))
        with self.assertRaisesRegex(ValueError, "clang-format 23.1.5 is required"):
            self.errors()

    def test_missing_clang_format_is_reported(self):
        self.setUp_repo()
        with self.assertRaisesRegex(ValueError, "not found"):
            STYLE.check(self.root, str(self.root / "missing"))

    def test_real_tree_is_clean(self):
        binary = ROOT / ".venv/bin/clang-format"
        if not binary.is_file():
            self.skipTest("project .venv has no clang-format")
        errors, count = STYLE.check(ROOT, str(binary))
        self.assertEqual(errors, [])
        self.assertGreater(count, 100)


if __name__ == "__main__":
    unittest.main()
